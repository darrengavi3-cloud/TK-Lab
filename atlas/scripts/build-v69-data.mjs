function projectFangzhen(row, readerDisplayStatus, auditRow = null) {
  const projected = {};
  for (const field of fangzhenReaderFields) if (row[field] !== undefined && row[field] !== '') projected[field] = row[field];
  projected.id = text(row.id);
  projected.commander = text(row.commander || row.name || auditRow?.commander);
  projected.title = normalizeFangzhenOfficeTitle(text(row.title || row.commission || auditRow?.title));
  projected.commission = normalizeFangzhenOfficeTitle(text(row.commission || row.title || auditRow?.title));
  projected.jurisdiction = text(row.jurisdiction || row.region || auditRow?.jurisdiction);
  projected.startYear = Number.isInteger(row.startYear) ? row.startYear : (Number.isInteger(auditRow?.startYear) ? auditRow.startYear : null);
  projected.endYear = Number.isInteger(row.endYear) ? row.endYear : (Number.isInteger(auditRow?.endYear) ? auditRow.endYear : null);
  projected.polity = text(row.polity || auditRow?.polity);
  projected.readerDisplayStatus = readerDisplayStatus;
  projected.jurisdictionKind = classifyFangzhenJurisdiction(projected);
  if (projected.polity === '汉') {
    projected.dynastyLabel = auditRow?.dataset === 'shu-screenshot' ? '季汉' : classifyFangzhenDynasty(projected);
    if (projected.dynastyLabel === '汉') projected.dynastyLabel = readerDisplayStatus === 'candidate' ? '后汉' : classifyFangzhenDynasty(projected);
  } else if (projected.polity === '晋') {
    projected.dynastyLabel = projected.eraGroup === 'eastjin' ? '东晋' : '西晋';
  } else projected.dynastyLabel = projected.polity;
  if (readerDisplayStatus === 'candidate') {
    delete projected.seat;
    delete projected.seatName;
    delete projected.seatType;
    delete projected.seatPeriodId;
    delete projected.administrativeUnitId;
    delete projected.seatValidFromYear;
    delete projected.seatValidToYear;
  }
  if (!projected.personId) projected.personId = uniquePersonIdForName(projected.commander) || undefined;
  return projected;
}
