function maximalExplicitNameTerms(value) {
  const candidates = explicitNameTerms
    .map(([name, ids]) => ({ name, ids, start: value.indexOf(name) }))
    .filter(item => item.start >= 0)
    .sort((left, right) => right.name.length - left.name.length || left.start - right.start || compareText(left.name, right.name));
  const occupied = [];
  const selected = [];
  for (const candidate of candidates) {
    const end = candidate.start + candidate.name.length;
    if (occupied.some(range => candidate.start < range.end && end > range.start)) continue;
    occupied.push({ start: candidate.start, end });
    selected.push(candidate);
  }
  return selected;
}
